DROP TABLE IF EXISTS cortesia CASCADE;
DROP TABLE IF EXISTS pesquisa_ativacao CASCADE;
DROP TABLE IF EXISTS auditoria CASCADE;
DROP TABLE IF EXISTS documento CASCADE;
DROP TABLE IF EXISTS patrocinio CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS patrocinador CASCADE;
DROP TABLE IF EXISTS evento CASCADE;

CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano SMALLINT NOT NULL UNIQUE CHECK (ano BETWEEN 2000 AND 2100)
);

CREATE TABLE patrocinador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    nome VARCHAR(255) NOT NULL,
    segmento VARCHAR(255),
    contato_principal VARCHAR(100),
    telefone VARCHAR(20),
    observacoes TEXT,
    status VARCHAR(10) NOT NULL DEFAULT 'ATIVO' CHECK (status IN ('ATIVO', 'INATIVO')),
    data_hora_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_hora_alteracao TIMESTAMPTZ
);


CREATE TABLE patrocinio (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_evento BIGINT NOT NULL REFERENCES evento (id),
    id_patrocinador BIGINT NOT NULL REFERENCES patrocinador (id),
    cota VARCHAR(30) NOT NULL CHECK (cota IN ('MASTER', 'SUBCOTA_G', 'SUBCOTA')),
    data_hora_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_hora_alteracao TIMESTAMPTZ,
    CONSTRAINT uq_patrocinio_evento_patrocinador UNIQUE (id_evento, id_patrocinador)
);


CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinador BIGINT REFERENCES patrocinador (id),
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    senha VARCHAR(255) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('ADMIN', 'PATROCINADOR')),
    data_hora_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_hora_alteracao TIMESTAMPTZ,
    CONSTRAINT ck_usuario_vinculo_patrocinador
    CHECK ((tipo = 'ADMIN' AND id_patrocinador IS NULL)
    OR (tipo = 'PATROCINADOR' AND id_patrocinador IS NOT NULL))
);

CREATE TABLE documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinio BIGINT NOT NULL REFERENCES patrocinio (id),
    id_usuario_envio BIGINT NOT NULL REFERENCES usuario (id),
    nome_arquivo VARCHAR(255) NOT NULL,
    categoria VARCHAR(30) NOT NULL
    CHECK (categoria IN (
            'FORMULARIO_INGRESSOS',
            'MIV',
            'LOGOTIPO',
            'FOTO_APLICACAO_MARCA',
            'RELATORIO_MIDIA',
            'PLANO_COMERCIAL',
            'CONTRATO',
            'OUTRO'
        )),
    chave_armazenamento VARCHAR(500) NOT NULL UNIQUE,
    tipo_mime VARCHAR(100) NOT NULL,
    tamanho_bytes BIGINT NOT NULL CHECK (tamanho_bytes > 0),
    origem VARCHAR(20) NOT NULL CHECK (origem IN ('PATROCINADOR', 'ADMIN')),
    data_hora_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_documento_patrocinio_categoria UNIQUE (id_patrocinio, categoria)
);

CREATE TABLE auditoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES usuario (id) ON DELETE SET NULL,
    nome_usuario VARCHAR(100) NOT NULL,
    email_usuario VARCHAR(100) NOT NULL,
    acao VARCHAR(50) NOT NULL,
    entidade VARCHAR(50) NOT NULL,
    id_entidade BIGINT,
    nome_recurso VARCHAR(255),
    data_hora TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE pesquisa_ativacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinio BIGINT NOT NULL UNIQUE REFERENCES patrocinio (id),
    pergunta_1 VARCHAR(500) NOT NULL,
    pergunta_2 VARCHAR(500) NOT NULL,
    pergunta_3 VARCHAR(500) NOT NULL,
    data_hora_criacao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_hora_alteracao TIMESTAMPTZ
);

CREATE TABLE cortesia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_patrocinio BIGINT NOT NULL REFERENCES patrocinio (id),
    setor VARCHAR(20) NOT NULL
    CHECK (setor IN (
        'ARENA',
        'CAMAROTE',
        'PREMIUM',
        'ROOFTOP',
        'TERRACO'
    )),
    tipo VARCHAR(20) NOT NULL
    CHECK (tipo IN (
        'SEXTA',
        'SABADO',
        'PASSAPORTE'
    )),
    quantidade INTEGER NOT NULL CHECK (quantidade >= 0),
    CONSTRAINT uk_cortesia_patrocinio_setor_tipo UNIQUE (id_patrocinio, setor, tipo)
);